    public static void ForceSetForegroundWindow(IntPtr hWnd)
    {
        if (hWnd == IntPtr.Zero) return;

        if (IsIconic(hWnd))
        {
            ShowWindowAsync(hWnd, SW_RESTORE);
        }
        else
        {
            ShowWindowAsync(hWnd, SW_SHOW);
        }

        IntPtr fgWnd = GetForegroundWindow();
        if (fgWnd != hWnd && fgWnd != IntPtr.Zero)
        {
            uint fgThread = GetWindowThreadProcessId(fgWnd, out _);
            uint currentThread = Kernel32.GetCurrentThreadId();

            if (fgThread != currentThread && fgThread != 0)
            {
                AttachThreadInput(currentThread, fgThread, true);
                BringWindowToTop(hWnd);
                SetForegroundWindow(hWnd);
                AttachThreadInput(currentThread, fgThread, false);
                return;
            }
        }

        BringWindowToTop(hWnd);
        SetForegroundWindow(hWnd);
    }
